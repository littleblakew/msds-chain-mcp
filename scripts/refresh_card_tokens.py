#!/usr/bin/env python3
"""Regenerate `msds_mcp/ui_card_tokens.py`: the colour roles the inline cards use, copied from
the web app's design tokens so the cards and the web app's result cards share one palette.

The cards are self-contained HTML (the host's CSP allows no external stylesheet), so the values
have to be inside the template. They are generated, never typed by hand: a hand copy drifts
silently. `tests/contract/test_card_tokens.py` regenerates from the same sources and compares
when the sources are available (it skips in a clone that has only this repository).

Sources, in override order (later wins), each given by an environment variable:
  CARD_TOKENS_SHELL_CSS  the design package's `tokens.css` (dark values under `:root`)
  CARD_TOKENS_WEB_DIR    the web frontend directory: `src/index.css` (`:root` overrides and the
                         `html.light` block) and `tailwind.config.js` (semantic fill colours)

    CARD_TOKENS_SHELL_CSS=... CARD_TOKENS_WEB_DIR=... python3 scripts/refresh_card_tokens.py
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "msds_mcp" / "ui_card_tokens.py"

# The roles the card template uses. A role missing from the sources is an error, not a skip:
# a card colour that silently falls back to the browser default looks like a design choice.
ROLES = ("surface", "inset", "field", "line", "line-strong", "label", "label-2", "label-3",
         "brand-ink", "brand-500", "warn-ink", "bad-ink", "ok-ink", "info-ink", "pending-ink")
TONES = ("ok", "warn", "bad", "info", "pending")

_VAR = re.compile(r"--s-([a-z0-9-]+)\s*:\s*([^;]+);")


def _strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def _block(css: str, selector: str) -> str:
    """Bodies of every rule whose selector is exactly `selector`, in source order (a later
    block overrides an earlier one, as in the browser)."""
    bodies = re.findall(r"(?<![\w.:-])" + re.escape(selector) + r"\s*\{([^}]*)\}", css)
    if not bodies:
        raise SystemExit(f"no `{selector}` block found")
    return "\n".join(bodies)


def _vars(body: str) -> dict[str, str]:
    return {k: " ".join(v.split()) for k, v in _VAR.findall(body)}


def collect(shell_css: str, web_index_css: str, tailwind_config: str) -> tuple[dict, dict, dict]:
    shell_css, web_index_css = _strip_comments(shell_css), _strip_comments(web_index_css)
    dark = _vars(_block(shell_css, ":root"))
    dark.update(_vars(_block(web_index_css, ":root")))
    light = {**dark, **_vars(_block(web_index_css, "html.light"))}
    fills = {}
    for tone in TONES:
        m = re.search(tone + r"\s*:\s*\{\s*DEFAULT\s*:\s*'#([0-9a-fA-F]{6})'", tailwind_config)
        if not m:
            raise SystemExit(f"no DEFAULT colour for `{tone}` in tailwind.config.js")
        h = m.group(1)
        fills[tone] = " ".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))
    missing = [r for r in ROLES if r not in dark]
    if missing:
        raise SystemExit(f"roles missing from the sources: {missing}")
    return ({r: dark[r] for r in ROLES}, {r: light[r] for r in ROLES}, fills)


def render(dark: dict, light: dict, fills: dict) -> str:
    def decls(values: dict) -> str:
        return "".join(f"--s-{k}:{v};" for k, v in values.items())
    # Semantic fills (`bg-bad/10` on the web) are one value for both themes, as on the web.
    tint_decls = "".join(f"--c-{k}:{v};" for k, v in fills.items())
    light_decls = decls({k: v for k, v in light.items() if dark.get(k) != v})
    css = (f":root{{{decls(dark)}{tint_decls}}}"
           f"@media (prefers-color-scheme:light){{:root:not([data-theme=dark]){{{light_decls}}}}}"
           f":root[data-theme=light]{{{light_decls}}}")
    return ('"""Generated by scripts/refresh_card_tokens.py from the web app\'s design tokens.\n'
            'Do not edit by hand; regenerate. Guarded by tests/contract/test_card_tokens.py."""\n\n'
            f"CARD_TOKENS_CSS = {css!r}\n")


def generate() -> str:
    shell = os.environ.get("CARD_TOKENS_SHELL_CSS")
    web = os.environ.get("CARD_TOKENS_WEB_DIR")
    if not shell or not web:
        raise SystemExit("set CARD_TOKENS_SHELL_CSS and CARD_TOKENS_WEB_DIR")
    web_dir = Path(web)
    return render(*collect(Path(shell).read_text(encoding="utf-8"),
                           (web_dir / "src" / "index.css").read_text(encoding="utf-8"),
                           (web_dir / "tailwind.config.js").read_text(encoding="utf-8")))


if __name__ == "__main__":
    OUT.write_text(generate(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}", file=sys.stderr)
